INSERT INTO `t_inventory_record`
(`inventory_id`, `change_type`, `change_quantity`, `before_stock`, `after_stock`, `order_id`, `remark`, `operator_id`, `create_time`)
SELECT
    i.id,
    m.change_type,
    m.qty,
    SUM(m.signed_qty) OVER (PARTITION BY m.dish_id ORDER BY m.seq) - m.signed_qty,
    SUM(m.signed_qty) OVER (PARTITION BY m.dish_id ORDER BY m.seq),
    m.order_id,
    m.remark,
    m.operator_id,
    m.create_time
FROM `tmp_stock_move` m
JOIN `t_inventory` i ON i.dish_id = m.dish_id AND i.deleted = 0;

UPDATE `t_inventory` i
JOIN (
    SELECT inventory_id, after_stock
    FROM (
        SELECT inventory_id, after_stock,
               ROW_NUMBER() OVER (PARTITION BY inventory_id ORDER BY create_time DESC, id DESC) AS rn
        FROM `t_inventory_record`
    ) latest
    WHERE rn = 1
) r ON r.inventory_id = i.id
SET i.current_stock = r.after_stock,
    i.last_in_time = (
        SELECT MAX(r2.create_time) FROM `t_inventory_record` r2
        WHERE r2.inventory_id = i.id AND r2.change_type = 1
    ),
    i.last_out_time = (
        SELECT MAX(r3.create_time) FROM `t_inventory_record` r3
        WHERE r3.inventory_id = i.id AND r3.change_type = 2
    );

UPDATE `t_dish` d
JOIN `t_inventory` i ON i.dish_id = d.id AND i.deleted = 0
SET d.stock = i.current_stock;

